#!/usr/bin/env node
/**
 * Emits a redirect for every URL docs.arbitrum.io serves today.
 *
 * Docusaurus serves `docs/**` at the site root (`routeBasePath: '/'`); this site serves the same
 * pages under `/docs`. Nothing in `redirects.legacy.mjs` covers that — those entries are upstream's
 * own pre-restructure map — so on cutover every indexed URL would 404. This closes that.
 *
 * Sources come from the sibling arbitrum-docs repo read through `git`, not the filesystem, so a
 * dirty working copy over there cannot leak into the output and `--ref` makes a run reproducible.
 * Destinations come from `content/docs` and are emitted only when the page provably exists; the rest
 * land in the `.todo.json` worklist, because a redirect to a merely-plausible page is worse than a
 * 404 — it silently sends readers somewhere wrong and no checker can detect it.
 *
 * The output is committed, so builds never need the sibling repo — only regeneration does.
 *
 * Usage:
 *   node scripts/generate-current-redirects.mjs [--repo <path>] [--ref <rev>] [--json]
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

import {
  buildCurrentRedirects,
  docusaurusRoute,
  findCollisions,
  findLoops,
  isRoutablePage,
  parseFrontmatter,
} from './lib/current-redirects.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_REPO = resolve(ROOT, '../arbitrum-docs');
const OUT_REDIRECTS = join(ROOT, 'redirects.current.mjs');
const OUT_TODO = join(ROOT, 'redirects.current.todo.json');
const CONTENT_DIR = join(ROOT, 'content/docs');

/**
 * The port window used by `pnpm drift`. A page added upstream after it was never in scope for the
 * migration (DRIFT); one added before it should have been ported and was not (MISS). Labelling the
 * worklist this way is the difference between "15 gaps" and "15 gaps, 13 of which are new upstream
 * pages nobody has written here yet".
 */
const PORT_WINDOW_END = '2026-07-10';

const git = (repo, args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' });

/** Every routable upstream page at `ref`, as `{ rel, title, route }`. */
function readUpstream(repo, ref) {
  const listed = git(repo, ['ls-tree', '-r', '--name-only', ref, 'docs/']).trim().split('\n');
  const pages = [];
  for (const path of listed) {
    const rel = path.slice('docs/'.length);
    if (!path.startsWith('docs/') || !isRoutablePage(rel)) continue;
    const front = parseFrontmatter(git(repo, ['cat-file', '-p', `${ref}:${path}`]));
    pages.push({ rel, title: front.title ?? null, route: docusaurusRoute(rel, front) });
  }
  return pages;
}

/** `content/docs` as `Map<relPath, title>`; titles are the pairing evidence for slug fallbacks. */
function readDestination() {
  const pages = new Map();
  const walk = (dir, prefix) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full, `${prefix}${entry}/`);
      else if (entry.endsWith('.mdx') && !entry.startsWith('_')) {
        pages.set(prefix + entry, parseFrontmatter(readFileSync(full, 'utf8')).title ?? null);
      }
    }
  };
  walk(CONTENT_DIR, '');
  return pages;
}

/** Date a page first appeared upstream, used to tell drift from a missed port. */
function addedDate(repo, ref, path) {
  const log = git(repo, ['log', ref, '--diff-filter=A', '--format=%ad', '--date=short', '--', path])
    .trim()
    .split('\n');
  return log[log.length - 1] || null;
}

function render(redirects) {
  const body = redirects
    .map(
      (r) =>
        `  {\n    source: '${r.source}',\n    destination: '${r.destination}',\n` +
        `    permanent: ${r.permanent},\n  },`,
    )
    .join('\n');
  return (
    `// GENERATED by scripts/generate-current-redirects.mjs — do not edit by hand.\n` +
    `// Regenerate with \`pnpm redirects:current\`.\n` +
    `//\n` +
    `// Every URL docs.arbitrum.io serves today (Docusaurus, root-level) -> this site's /docs paths.\n` +
    `// Distinct from redirects.legacy.mjs, which ports upstream's own pre-restructure redirect map.\n` +
    `// Unresolvable pages are listed in redirects.current.todo.json.\n` +
    `//\n` +
    `// permanent: true (308) throughout. Moving the whole corpus under /docs is a permanent site\n` +
    `// restructure, and 308 is what passes the old URLs' search ranking to the new ones — the point\n` +
    `// of the exercise. The legacy generator copies upstream's per-entry flag instead because it is\n` +
    `// porting someone else's decisions; here there is no upstream flag to copy.\n` +
    `/** @type {{ source: string, destination: string, permanent: boolean }[]} */\n` +
    `export const currentRedirects = [\n${body}\n];\n`
  );
}

/** Write through Prettier so generated output never trips `pnpm format:check`. */
async function writeFormatted(filePath, contents) {
  const config = await resolveConfig(filePath);
  writeFileSync(filePath, await format(contents, { ...config, filepath: filePath }));
}

/**
 * The redirects already in the final array, minus this generator's previous output.
 *
 * `redirects.config.mjs` spreads `currentRedirects` in, so importing it naively would compare this
 * run against the last one and report every entry as a collision. The spread preserves object
 * identity, so the previous generation can be subtracted by reference.
 */
async function readExisting() {
  const { redirects } = await import(join(ROOT, 'redirects.config.mjs'));
  let previous = new Set();
  try {
    const mod = await import(join(ROOT, 'redirects.current.mjs'));
    previous = new Set(mod.currentRedirects);
  } catch {
    // First run: the file does not exist yet, so nothing to subtract.
  }
  return redirects.filter((entry) => !previous.has(entry));
}

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = argv.indexOf(name);
  return i === -1 ? fallback : argv[i + 1];
};
const repo = resolve(flag('--repo', DEFAULT_REPO));
const ref = flag('--ref', 'HEAD');
const asJson = argv.includes('--json');

const resolvedRef = git(repo, ['rev-parse', '--short', ref]).trim();
const pages = readUpstream(repo, ref);
const destPages = readDestination();
const existing = await readExisting();
const { redirects, todo, excluded, deferred, byRule } = buildCurrentRedirects({
  pages,
  destPages,
  existing: new Map(existing.map((entry) => [entry.source, entry.destination])),
});

for (const item of todo) {
  item.added = addedDate(repo, ref, item.upstream);
  item.kind = item.added && item.added > PORT_WINDOW_END ? 'DRIFT' : 'MISS';
}

const combined = [...existing, ...redirects];
const collisions = findCollisions(combined);
const loops = findLoops(combined);

await writeFormatted(OUT_REDIRECTS, render(redirects));
await writeFormatted(OUT_TODO, JSON.stringify(todo, null, 2));

const report = {
  repo,
  ref: resolvedRef,
  upstreamPages: pages.length,
  destinationPages: destPages.size,
  emitted: redirects.length,
  unresolved: todo.length,
  deferred,
  excluded,
  byRule: Object.fromEntries(Object.entries(byRule).map(([k, v]) => [k, v.length])),
  collisions,
  loops,
  todo,
};

if (asJson) {
  console.log(JSON.stringify(report, null, 2));
} else {
  console.error(`repo            : ${repo} @ ${resolvedRef}`);
  console.error(`upstream pages  : ${pages.length} routable`);
  console.error(`site pages      : ${destPages.size}`);
  console.error(`emitted         : ${redirects.length}  -> redirects.current.mjs`);
  console.error(`  mapped        : ${byRule.mapped.length} (directory + slug, via tree-compare)`);
  console.error(`  bare-slug     : ${byRule['bare-slug'].length} (cross-directory, titles agree)`);
  console.error(`  title         : ${byRule.title.length} (unique exact title match)`);
  console.error(`  manual        : ${byRule.manual.length} (hand-confirmed + sidebar indexes)`);
  console.error(`deferred        : ${deferred.length} (source already redirected elsewhere)`);
  console.error(`unresolved      : ${todo.length}  -> redirects.current.todo.json`);
  console.error(`collisions      : ${collisions.length}`);
  console.error(`loops           : ${loops.length}`);
  for (const item of excluded) console.error(`excluded        : ${item.source} — ${item.reason}`);
  for (const d of deferred) {
    console.error(
      `deferred        : ${d.source} -> ${d.existing}${d.conflict ? ` CONFLICT (derived ${d.destination})` : ''}`,
    );
  }

  if (byRule.title.length) {
    console.error(`\nmatched on title alone (${byRule.title.length}) — review these:`);
    for (const r of byRule.title) console.error(`  ${r.source}\n    => ${r.destination}`);
  }
  if (todo.length) {
    console.error(`\nNO REDIRECT (${todo.length}) — these URLs will 404 on cutover:`);
    for (const t of todo) {
      console.error(`  ${t.kind}  added ${t.added ?? 'unknown'}  ${t.source}`);
      console.error(`      ${t.reason}${t.wouldMatch ? ` (rejected ${t.wouldMatch})` : ''}`);
    }
  }
}

if (collisions.length) {
  console.error(`\ngenerate-current-redirects: duplicate sources in the final array:`);
  for (const c of collisions) console.error(`  ${c.source} (${c.count}x)`);
  process.exitCode = 1;
}
if (loops.length) {
  console.error(`\ngenerate-current-redirects: redirect loops in the final array:`);
  for (const l of loops) console.error(`  ${l.kind}  ${l.source} -> ${l.destination}`);
  process.exitCode = 1;
}
