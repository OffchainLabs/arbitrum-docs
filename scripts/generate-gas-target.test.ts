/**
 * Tests for the gas-target partial renderer and the snapshot validator.
 *
 * Fixture snapshots stand in for `scripts/data/gas-target.json` so the assertions stay pinned to
 * the markdown shape rather than to whatever the chains report today: a changed target should
 * show up as a diff in the generated partial, never as a red test. Nothing here imports either
 * runner; both are a dozen lines of wiring over the functions tested below.
 */
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import {
  type Chain,
  type GasTargetsSnapshot,
  buildContent,
  formatMgas,
  validateSnapshot,
} from './lib/gas-target.ts';
import { assertInertMdx } from './lib/generated-partial.ts';

const CHAINS: Chain[] = [
  { key: 'multi', label: 'Multi Chain', rpcUrl: 'https://multi.example/rpc' },
  { key: 'single', label: 'Single Chain', rpcUrl: 'https://single.example/rpc' },
];

const SNAPSHOT: GasTargetsSnapshot = {
  multi: {
    constraints: [
      [60_000_000, 9],
      [7_500_000, 2_105],
      [10_000_000, 86_400],
    ],
  },
  single: { speedLimit: 7_000_000 },
};

describe('formatMgas', () => {
  it('renders a target divisible by 1e6 as an integer', () => {
    assert.equal(formatMgas(60_000_000), '60');
  });

  it('renders any other target with one decimal', () => {
    assert.equal(formatMgas(7_500_000), '7.5');
  });
});

describe('buildContent', () => {
  const content = buildContent(SNAPSHOT, CHAINS);

  it('opens with the do-not-edit marker and no ## heading', () => {
    assert.match(
      content,
      /^\{\/\* AUTOGENERATED\. Do not edit by hand\. Run `pnpm gas-target:generate` after running pnpm gas-target:fetch\. \*\/\}\n/,
    );
    assert.doesNotMatch(content, /^## /m);
  });

  it('renders a multi-constraint chain as a table under its own ### heading', () => {
    assert.match(
      content,
      /### Multi Chain\n\n\| Gas target \(Mgas\/s\) \| Adjustment window \(seconds\) \|\n\| --- \| --- \|\n\| \*\*60\*\* \| 9 \|\n/,
    );
  });

  it('formats a non-round target with one decimal and a window with thousands separators', () => {
    assert.match(content, /\| \*\*7\.5\*\* \| 2,105 \|\n\| \*\*10\*\* \| 86,400 \|\n/);
  });

  it('renders a single-target chain as one sentence', () => {
    assert.match(
      content,
      /### Single Chain\n\nSingle Chain uses a single gas target of 7,000,000 gas\/s \(7 Mgas\/s\) and no adjustment windows\.\n/,
    );
  });

  it('keeps the chain order it was given', () => {
    assert.ok(content.indexOf('### Multi Chain') < content.indexOf('### Single Chain'));
  });

  it('passes assertInertMdx with no element allowed', () => {
    assertInertMdx(content, { context: 'test', allowedElements: [] });
  });
});

describe('validateSnapshot', () => {
  const reject = (chain: unknown, message: RegExp): void => {
    assert.throws(
      () => validateSnapshot({ multi: SNAPSHOT.multi, single: chain }, CHAINS),
      message,
    );
  };

  it('returns the snapshot typed when every chain is well formed', () => {
    assert.deepEqual(validateSnapshot(SNAPSHOT, CHAINS), SNAPSHOT);
  });

  it('rejects a missing chain', () => {
    assert.throws(() => validateSnapshot({ multi: SNAPSHOT.multi }, CHAINS), /single: missing/);
  });

  it('rejects a non-integer target', () => {
    reject({ constraints: [[7.5, 9]] }, /single: constraints\[0\]: target: expected an integer/);
  });

  it('rejects a zero window', () => {
    reject(
      { constraints: [[7_000_000, 0]] },
      /single: constraints\[0\]: window: expected a positive/,
    );
  });

  it('rejects a negative speedLimit', () => {
    reject({ speedLimit: -1 }, /single: speedLimit: expected a positive integer/);
  });

  it('rejects a non-integer speedLimit', () => {
    reject({ speedLimit: '7000000' }, /single: speedLimit: expected an integer/);
  });

  it('rejects empty constraints with no speedLimit', () => {
    reject({ constraints: [] }, /single: constraints must be a non-empty array/);
  });

  it('rejects a chain with neither field', () => {
    reject({}, /single: has neither constraints nor speedLimit/);
  });

  it('rejects a chain with both fields', () => {
    reject(
      { constraints: [[7_000_000, 9]], speedLimit: 7_000_000 },
      /single: has both constraints and speedLimit/,
    );
  });

  it('rejects a constraint row that is not a pair', () => {
    reject(
      { constraints: [[7_000_000, 9, 0]] },
      /single: constraints\[0\]: expected \[target, window\]/,
    );
  });
});
